#!/bin/sh
# corex test suite. gdb is the oracle: for every fact corex prints about a
# core, gdb is asked the same question about the same core and the two answers
# are compared. readelf is the oracle for the ELF container itself.
set -u
cd "$(dirname "$0")/.." || exit 1
COREX=${COREX:-./corex}
PWD=$(pwd)
S=scratch
mkdir -p $S || exit 1
printf 'corex under test: %s\n\n' "$COREX"

pass=0; fail=0; skip=0
ok()   { printf 'ok    %s\n' "$1"; pass=$((pass+1)); }
no()   { printf 'FAIL  %s\n' "$1"; fail=$((fail+1)); }
skip() { printf 'skip  %s\n' "$1"; skip=$((skip+1)); }
nz()   { sed 's/0x0*\([0-9a-f]\)/0x\1/g'; }   # 0x0000ab -> 0xab, so hex widths do not matter
chk()  { if [ "$2" = "$3" ]; then ok "$1"; else no "$1: got [$2] want [$3]"; fi; }

CFL="-O0 -g -fno-omit-frame-pointer -mno-omit-leaf-frame-pointer -fno-inline"
gdbb() { gdb --batch -nx -iex 'set debuginfod enabled off' "$@"; }

# Generate a core from t/$1.c by letting it die under gdb and calling gcore on
# the stopped inferior. /proc/sys/kernel/core_pattern pipes to systemd-coredump
# here and cannot be changed without root, so gcore is the only way to get a
# core at all; see README.
gen() {
	n=$1; shift
	gcc $CFL $@ -o $S/$n t/$n.c || { no "build t/$n.c"; return 1; }
	rm -f $S/core.$n
	gdbb -ex run -ex "gcore $S/core.$n" $S/$n >$S/gen.$n.log 2>&1
	[ -s $S/core.$n ] || { no "gcore produced no core for $n"; return 1; }
	return 0
}

gen seg || exit 1
ok "gcore: wrote a core for t/seg.c ($(stat -c%s $S/core.seg) bytes)"

# -- the ELF container, against readelf ------------------------------------
want=$(readelf -lW $S/core.seg | sed -n 's/^There are \([0-9]*\) program headers.*/\1/p')
got=$($COREX --phdrs $S/core.seg | sed -n 's/^core:.* \([0-9]*\) program headers.*/\1/p')
chk "phdr count agrees with readelf ($want)" "$got" "$want"

readelf -lW $S/core.seg | awk '$1=="LOAD"{print $3,$5,$6}' | nz | sort > $S/re.load
$COREX --phdrs $S/core.seg | awk '$3=="PT_LOAD"{print $7,$9,$11}' | nz | sort > $S/cx.load
if cmp -s $S/re.load $S/cx.load; then
	ok "every PT_LOAD vaddr/filesz/memsz agrees with readelf ($(wc -l <$S/re.load | tr -d ' ') segments)"
else
	no "PT_LOAD table disagrees with readelf"; diff $S/re.load $S/cx.load | head -5
fi

# -- the note list, against readelf -n ------------------------------------
# A note's name field is padded to 4 bytes and its descriptor is padded to 4
# bytes. An iterator that pads either one wrong still decodes the first note
# and then desyncs, so the test is the whole list, in order, to the last note.
readelf -n $S/core.seg | awk '/^  [A-Z]/ && $2 ~ /^0x/ {print $1, $2, $3}' | nz > $S/re.notes
$COREX --notes $S/core.seg | awk '$1=="note"{print $2, $3, $4}' | nz > $S/cx.notes
if cmp -s $S/re.notes $S/cx.notes; then
	ok "note list agrees with readelf -n, owner/size/type, in order ($(wc -l <$S/re.notes | tr -d ' ') notes)"
else
	no "note list disagrees with readelf -n"; diff $S/re.notes $S/cx.notes | head -8
fi

# -- NT_PRPSINFO, against gdb ---------------------------------------------
# gdb prints pr_psargs in its "Core was generated by" line and the pid in
# "info inferiors", both read out of the same note by an independent parser.
gdbb $S/seg $S/core.seg -ex 'info inferiors' >$S/gdb.proc 2>&1
want=$(sed -n "s/^Core was generated by \`\(.*\)'\\.$/\\1/p" $S/gdb.proc)
got=$($COREX --proc $S/core.seg | sed -n 's/^psargs: //p')
chk "psargs agrees with gdb ($want)" "$got" "$want"
want=$(awk '{for(i=1;i<NF;i++) if($i=="process") print $(i+1)}' $S/gdb.proc)
got=$($COREX --proc $S/core.seg | sed -n 's/^proc: pid \([0-9]*\) .*/\1/p')
chk "pid agrees with gdb ($want)" "$got" "$want"
got=$($COREX --proc $S/core.seg | sed -n 's/^cmd: //p')
chk "pr_fname is the program name" "$got" "seg"

# -- NT_PRSTATUS: registers, against gdb ----------------------------------
# Every general-purpose register, by value, against an independent reader of
# the same bytes. A register gdb disagrees with is conclusively wrong.
regs_of_gdb() {  # regs_of_gdb CORE BIN [thread-cmd]
	gdbb "$2" "$1" -ex "${3:-info registers}" -ex 'info registers orig_rax' 2>&1 |
		awk '$1 ~ /^[a-z_0-9]+$/ && $2 ~ /^0x/ {print $1, $2}' | nz | sort
}
regs_of_gdb $S/core.seg $S/seg > $S/gdb.regs
$COREX --regs $S/core.seg | awk '$1=="reg"{print $2, $3}' | nz | sort > $S/cx.regs
# Two different failures used to share one message. `[ "$n" -eq 27 ]` is a
# guard against a vacuous comparison -- if gdb printed nothing, cmp of two
# empty files succeeds -- but 27 is what *this* gdb prints for x86-64, and
# gdb's register list does change between versions (fs_base and gs_base
# joined `info registers` in 8.2). A newer gdb would have reported
# "registers disagree with gdb" about a corex that agreed with it on every
# register it was asked about. The guard is now a floor, which is all it has
# to be, and the count it saw is reported either way.
#
# NREGS is reused for the per-thread total below, so the two cannot drift
# apart: that one was hardcoded at 108, which is this number times 4 threads.
NREGS=$(wc -l <$S/gdb.regs | tr -d ' ')
if [ "$NREGS" -lt 16 ]; then
	no "gdb printed only $NREGS registers, so the comparison proves nothing"
elif cmp -s $S/gdb.regs $S/cx.regs; then
	ok "all $NREGS registers agree with gdb, by value"
else
	no "registers disagree with gdb ($NREGS from gdb)"; diff $S/gdb.regs $S/cx.regs | head
fi

# The comparator must be able to fail. Flip one nibble of rip in a copy of the
# core and confirm the register check notices: a suite that cannot fail is the
# most expensive kind of green.
cp $S/core.seg $S/core.tamper
off=$(python3 - $S/core.tamper <<'PY'
import struct, sys
b = bytearray(open(sys.argv[1], 'rb').read())
phoff, = struct.unpack_from('<Q', b, 0x20)
ps, pn = struct.unpack_from('<HH', b, 0x36)
for i in range(pn):
	t, fl, off, va, pa, fsz, msz, al = struct.unpack_from('<IIQQQQQQ', b, phoff + i * ps)
	if t != 4:
		continue
	p = off
	end = off + fsz
	while p + 12 <= end:
		nsz, dsz, ty = struct.unpack_from('<III', b, p)
		desc = p + 12 + ((nsz + 3) & ~3)
		if ty == 1:                 # NT_PRSTATUS: pr_reg[16] is rip
			b[desc + 112 + 16 * 8] ^= 0x10
			open(sys.argv[1], 'wb').write(b)
			print(desc)
			sys.exit()
		p = desc + ((dsz + 3) & ~3)
PY
)
[ -n "$off" ] || no "tamper helper found no NT_PRSTATUS"
$COREX --regs $S/core.tamper | awk '$1=="reg"{print $2, $3}' | nz | sort > $S/cx.tamper
if cmp -s $S/gdb.regs $S/cx.tamper; then
	no "meta: register comparator did not notice a flipped bit in rip"
else
	ok "meta: register comparator notices a flipped bit in rip"
fi

# -- the signal and the faulting address, against gdb ---------------------
gdbb $S/seg $S/core.seg -ex 'p $_siginfo' >$S/gdb.sig 2>&1
want=$(sed -n 's/^Program terminated with signal \([A-Z0-9]*\),.*/\1/p' $S/gdb.sig)
got=$($COREX --signal $S/core.seg | sed -n 's/^signal: \([A-Z0-9]*\) .*/\1/p')
chk "killing signal agrees with gdb ($want)" "$got" "$want"
want=$(tr ',' '\n' <$S/gdb.sig | sed -n 's/.*si_code = \(-*[0-9]*\).*/\1/p' | head -1)
got=$($COREX --signal $S/core.seg | sed -n 's/^signal: .* code \(-*[0-9]*\) .*/\1/p')
chk "si_code agrees with gdb \$_siginfo ($want)" "$got" "$want"
want=$(tr ',' '\n' <$S/gdb.sig | sed -n 's/.*_sigfault = {si_addr = \(0x[0-9a-f]*\).*/\1/p' | head -1)
got=$($COREX --signal $S/core.seg | sed -n 's/^fault: address //p')
chk "faulting address agrees with gdb \$_siginfo->si_addr ($want)" "$got" "$want"

# -- multiple threads ------------------------------------------------------
# One NT_PRSTATUS per thread. Getting the count or the order wrong is easy and
# nothing else in the output looks different when you do.
gen threads -pthread || exit 1
ok "gcore: wrote a core for t/threads.c"
gdbb $S/threads $S/core.threads -ex 'info threads' >$S/gdb.threads 2>&1

tidre='s/^[* ] *[0-9]* *Thread [^(]*(LWP \([0-9]*\)).*/\1/p'
want=$(sed -n "$tidre" $S/gdb.threads | wc -l | tr -d ' ')
got=$($COREX --threads $S/core.threads | sed -n 's/^threads: //p')
chk "thread count agrees with gdb ($want, built as 4)" "$got" "$want"
chk "thread count is the 4 the program creates" "$got" "4"

sed -n "$tidre" $S/gdb.threads | sort > $S/gdb.tids
$COREX --threads $S/core.threads | sed -n 's/^thread [0-9]* tid \([0-9]*\) .*/\1/p' | sort > $S/cx.tids
cmp -s $S/gdb.tids $S/cx.tids && ok "the set of tids agrees with gdb" || {
	no "tid set disagrees with gdb"; diff $S/gdb.tids $S/cx.tids; }
sed -n 's/^tid //p' $S/gen.threads.log | sort > $S/self.tids
cmp -s $S/self.tids $S/cx.tids && ok "...and with the tids the program printed itself" || {
	no "tid set disagrees with what the process reported via gettid()"
	diff $S/self.tids $S/cx.tids; }

# The signalled thread is written first, by both the kernel and gcore, and gdb
# marks it with '*'.
want=$(sed -n '/^\*/'"$tidre" $S/gdb.threads)
got=$($COREX --threads $S/core.threads | sed -n 's/^thread 1 tid \([0-9]*\) .*/\1/p')
chk "thread 1 is the thread that took the signal ($want)" "$got" "$want"
# Both the kernel and gcore stamp pr_cursig on *every* thread's NT_PRSTATUS,
# not only the one that faulted, so the signalled thread is identified by
# being written first and not by being the only one with a signal.
got=$($COREX --threads $S/core.threads | grep -c 'cursig 11')
chk "every thread's NT_PRSTATUS records the killing signal" "$got" "4"

# Every register of every thread, not just the crashing one. gdb numbers
# threads in core order, so gdb's thread N must be our thread N.
agree=0; bad=0
i=1
while [ $i -le 4 ]; do
	regs_of_gdb $S/core.threads $S/threads "thread apply $i info registers" >$S/gdb.r$i
	$COREX --regs $S/core.threads |
		awk -v t=$i '$1=="thread"{n=$2} $1=="reg" && n==t {print $2, $3}' |
		nz | sort > $S/cx.r$i
	if cmp -s $S/gdb.r$i $S/cx.r$i; then
		agree=$((agree + $(wc -l <$S/gdb.r$i | tr -d ' ')))
	else
		bad=$((bad + 1)); diff $S/gdb.r$i $S/cx.r$i | head -4
	fi
	i=$((i + 1))
done
# 4 threads times whatever this gdb reports per thread. This was 108, i.e.
# 4 x 27 for the gdb on the machine it was written on.
want=$((NREGS * 4))
if [ $bad -eq 0 ] && [ $agree -eq $want ]; then
	ok "all $agree registers of all 4 threads agree with gdb, thread by thread"
elif [ $bad -eq 0 ]; then
	no "4 threads agreed but on $agree values, not the $want expected ($NREGS x 4)"
else
	no "$bad of 4 threads disagree with gdb on registers ($agree values matched)"
fi

# -- NT_AUXV, against gdb's info auxv --------------------------------------
# gdb prints some auxv values in hex and some in decimal, and AT_PLATFORM with
# the string it points at, so both sides are reduced to (key, integer value)
# before comparing.
gdbb $S/seg $S/core.seg -ex 'info auxv' >$S/gdb.auxv 2>&1
$COREX --auxv $S/core.seg >$S/cx.auxv
if python3 - $S/gdb.auxv $S/cx.auxv <<'PY'
import re, sys

num = re.compile(r'^(0x[0-9a-fA-F]+|[0-9]+)$')

def gdb(path):
	out = []
	for line in open(path):
		f = line.split()
		if len(f) < 3 or not f[0].isdigit() or not f[1].startswith('AT_'):
			continue
		for tok in reversed(f[2:]):          # last numeric token is the value
			if num.match(tok):
				out.append((int(f[0]), int(tok, 0)))
				break
	return out

def cx(path):
	return [(int(f[1]), int(f[3], 16))
		for f in (l.split() for l in open(path)) if f and f[0] == 'auxv']

a, b = gdb(sys.argv[1]), cx(sys.argv[2])
if a != b:
	print('gdb:', a[:40])
	print('us :', b[:40])
	sys.exit(1)
PY
then
	ok "all $(grep -c '^auxv ' $S/cx.auxv) auxv entries agree with gdb, key and value"
else
	no "auxv disagrees with gdb"
fi

# -- NT_FILE, against gdb's info proc mappings -----------------------------
# On a core, gdb's "info proc mappings" *is* the NT_FILE note, so this
# compares two independent decodings of the same bytes, including the
# page_size multiplication on file_ofs.
gdbb $S/seg $S/core.seg -ex 'info proc mappings' 2>&1 |
	awk '$1 ~ /^0x/ {print $1, $2, $4, $5}' | nz | sort > $S/gdb.files
$COREX --files $S/core.seg | awk '$1=="file"{print $2, $3, $5, $6}' | nz | sort > $S/cx.files
if cmp -s $S/gdb.files $S/cx.files; then
	ok "all $(wc -l <$S/cx.files | tr -d ' ') NT_FILE mappings agree with gdb: start, end, file offset, name"
else
	no "NT_FILE disagrees with gdb"; diff $S/gdb.files $S/cx.files | head -6
fi

# -- the PT_LOAD map, against gdb's view of the same segments ---------------
# "maint info sections" on a core lists one BFD section per PT_LOAD with its
# address range, its file offset and whether it HAS_CONTENTS, which is
# p_filesz != 0. READONLY and CODE are gdb's reading of p_flags.
gdbb $S/seg $S/core.seg -ex 'maint info sections' 2>&1 | grep -E 'load[0-9]+' |
	awk '{ sub("->"," ",$2); c="absent"; ro="rw"; x="-"
	       for (i=1; i<=NF; i++) { if ($i=="HAS_CONTENTS") c="present"
	                               if ($i=="READONLY") ro="r-"
	                               if ($i=="CODE") x="x" }
	       print $2, c, ro x }' | nz | sort > $S/gdb.maps
$COREX --maps $S/core.seg |
	awk '$1=="map" { st=$9; if (st=="partial") st="present"; print $2, $3, st, $4 }' |
	nz | sort > $S/cx.maps
if cmp -s $S/gdb.maps $S/cx.maps; then
	ok "all $(wc -l <$S/cx.maps | tr -d ' ') PT_LOAD mappings agree with gdb: range, permissions, contents present"
else
	no "PT_LOAD map disagrees with gdb"; diff $S/gdb.maps $S/cx.maps | head -6
fi

# -- reading memory out of a PT_LOAD ---------------------------------------
# t/buf.c plants 64 KiB of known bytes on its stack and prints the address.
# The expected contents come from the source; gdb is asked for the same bytes
# as a second opinion.
gen buf || exit 1
addr=$(sed -n 's/^buf \(0x[0-9a-f]*\) .*/\1/p' $S/gen.buf.log)
if [ -z "$addr" ]; then
	no "t/buf.c did not report its buffer address"
else
	ok "gcore: wrote a core for t/buf.c, buffer at $addr"
	$COREX -x $addr,256 $S/core.buf | awk '{for (i=3; i<=NF && $i ~ /^[0-9a-f][0-9a-f]$/; i++) print $i}' > $S/cx.bytes
	python3 -c 'print("\n".join("%02x" % ((i*31+7) & 255) for i in range(256)))' > $S/src.bytes
	cmp -s $S/src.bytes $S/cx.bytes && ok "256 bytes read out of the stack segment are the bytes t/buf.c wrote" || {
		no "stack buffer contents are not what the source wrote"; diff $S/src.bytes $S/cx.bytes | head -4; }
	gdbb $S/buf $S/core.buf -ex "x/256xb $addr" 2>&1 |
		awk -F: '/^0x/{print $2}' | tr -s ' \t' '\n' | sed '/^$/d;s/^0x//' > $S/gdb.bytes
	cmp -s $S/gdb.bytes $S/cx.bytes && ok "...and are byte-identical to what gdb reads from the same core" || {
		no "stack bytes disagree with gdb"; diff $S/gdb.bytes $S/cx.bytes | head -4; }
	got=$($COREX --maps $S/core.buf | python3 -c '
import sys
a = int(sys.argv[1], 16)
for l in sys.stdin:
	f = l.split()
	if f[0] == "map" and int(f[1], 16) <= a < int(f[2], 16):
		print(f[3], f[8])
' $addr)
	chk "the mapping that holds the buffer is rw- and present" "$got" "rw- present"
fi

# An address no PT_LOAD covers is an error, not an empty dump.
$COREX -x 0x1,16 $S/core.seg >$S/out 2>&1; rc=$?
chk "reading an unmapped address fails (exit 1)" "$rc" "1"
grep -q unmapped $S/out && ok "and says the address is unmapped" || no "no diagnostic for unmapped read"

# -- the backtrace, against gdb's bt ---------------------------------------
# Two comparisons. The frame addresses, which are ours, must equal gdb's frame
# for frame; and the function names, which are gdb's (corex deliberately has no
# symbol table reader -- see README), must come out in the same order. Naming
# our addresses with "info symbol" and naming gdb's frames with "bt" are
# separate code paths in gdb, so agreeing is not circular.
bt_gdb() {   # bt_gdb CORE BIN [cmd]
	# gdb prints frame #0 once in its "Program terminated" preamble and again
	# in the backtrace, so everything before the marker is dropped.
	gdbb "$2" "$1" -ex 'set print frame-info location-and-address' \
		-ex 'echo @@@\n' -ex "${3:-bt}" 2>&1 | sed -n '/^@@@/,$p' |
		sed -n 's/^#[0-9]* *\(0x[0-9a-f]*\) .*/\1/p' | nz
}
bt_cx() {    # bt_cx CORE THREAD
	$COREX --bt "$1" | awk -v t="$2" '/^bt thread/ { on = ($3 == t) }
	                                  /^#/ { if (on) print $2 }' | nz
}
bt_names_gdb() {
	gdbb "$2" "$1" -ex 'echo @@@\n' -ex "${3:-bt}" 2>&1 | sed -n '/^@@@/,$p' |
		sed -n 's/^#[0-9]* .* in \([A-Za-z_][A-Za-z_0-9]*\) (.*/\1/p'
}
bt_names_of_addrs() {   # bt_names_of_addrs CORE BIN < addrs
	c=$1; b=$2
	set -- ; while read -r a; do set -- "$@" -ex "info symbol $a"; done
	gdbb "$b" "$c" "$@" 2>&1 | sed -n 's/^\([A-Za-z_][A-Za-z_0-9]*\) \(+ [0-9]* \)*in section .*/\1/p'
}

# corex's frames must be a subsequence of gdb's, in order: it may skip a
# frame whose function does not maintain rbp, but it must never invent one,
# reorder two, or report an address gdb does not have.
bt_subseq() {   # bt_subseq GDB_ADDRS CX_ADDRS
	python3 - "$1" "$2" <<'PY'
import sys

g = [l.strip() for l in open(sys.argv[1]) if l.strip()]
c = [l.strip() for l in open(sys.argv[2]) if l.strip()]
i = 0
for a in c:
	while i < len(g) and g[i] != a:
		i += 1
	if i == len(g):
		print("frame %s is not in gdb's backtrace, or is out of order" % a)
		sys.exit(1)
	i += 1
sys.exit(0)
PY
}

bt_gdb $S/core.seg $S/seg > $S/gdb.bt
bt_cx $S/core.seg 1 > $S/cx.bt
n=$(wc -l <$S/cx.bt | tr -d ' ')
if [ "$n" -eq 5 ] && cmp -s $S/gdb.bt $S/cx.bt; then
	ok "all $n backtrace frame addresses agree with gdb, in order (t/seg.c is 4 deep plus main)"
else
	no "backtrace disagrees with gdb"; diff $S/gdb.bt $S/cx.bt
fi
bt_names_of_addrs $S/core.seg $S/seg <$S/cx.bt > $S/cx.names
bt_names_gdb $S/core.seg $S/seg > $S/gdb.names
chk "the frames name d c b a main, in that order" "$(tr '\n' ' ' <$S/cx.names)" "d c b a main "
cmp -s $S/gdb.names $S/cx.names && ok "and gdb's bt names the same functions in the same order" || {
	no "frame function names disagree with gdb"; diff $S/gdb.names $S/cx.names; }

# Per thread, on the four-thread core. Here corex is allowed to stop early
# but never to differ: its frame list must be a *prefix* of gdb's. gdb unwinds
# libc with CFI out of .eh_frame and so walks on through start_thread into
# __GI___clone3, which has no frame pointer to follow; corex stops when the
# chain runs out. Dropping a frame honestly is a documented limitation.
# Inventing or reordering one would be a bug, and this is the check that would
# catch it.
bad=0; ours=0; theirs=0
i=1
while [ $i -le 4 ]; do
	bt_gdb $S/core.threads $S/threads "thread apply $i bt" > $S/gdb.bt$i
	bt_cx $S/core.threads $i > $S/cx.bt$i
	k=$(wc -l <$S/cx.bt$i | tr -d ' ')
	bt_subseq $S/gdb.bt$i $S/cx.bt$i || bad=$((bad+1))
	ours=$((ours + k)); theirs=$((theirs + $(wc -l <$S/gdb.bt$i | tr -d ' ')))
	i=$((i+1))
done
if [ $bad -eq 0 ] && [ $ours -gt 0 ]; then
	ok "all $ours frames of all 4 threads are frames gdb also reports, in order (gdb reaches $theirs; the rest are frame-pointerless libc frames)"
else
	no "$bad of 4 thread backtraces differ from gdb's ($ours vs $theirs frames)"
fi

# Each of the three spinning threads must be in its own function.
$COREX --bt $S/core.threads | awk '/^bt thread/ { on = ($3 ~ /^[0-9]+$/) }
                                   /^#0/ { if (on) print $2 }' > $S/cx.tops
got=$(bt_names_of_addrs $S/core.threads $S/threads <$S/cx.tops | sort | tr '\n' ' ')
chk "the four threads are in four different functions" "$got" "main th_alpha th_beta th_gamma "

# -- the command line and the environment ----------------------------------
# No note carries either one, so they are dug out of the initial stack frame.
# The oracle is that the test *chooses* them: the core is made with a known
# argv and, via env -i, an environment of exactly four variables. Anything
# corex reports that was not put there is wrong, and anything missing is too.
rm -f $S/core.args
env -i COREX_MARK=hello PATH=/usr/bin HOME=/nonexistent LC_ALL=C \
	gdb --batch -nx -iex 'set debuginfod enabled off' \
	    -ex 'run alpha beta gamma' -ex "gcore $S/core.args" $S/seg \
	    >$S/gen.args.log 2>&1
if [ ! -s $S/core.args ]; then
	no "could not make a core with a controlled argv and environment"
else
	ok "gcore: wrote a core with a known argv and a 4-variable environment"
	$COREX --cmdline $S/core.args > $S/cx.cmd
	got=$(sed -n 's/^arg [0-9]* //p' $S/cx.cmd | tr '\n' ' ')
	chk "argv recovered from the stack" "$got" "$PWD/$S/seg alpha beta gamma "
	chk "argc agrees" "$(sed -n 's/^cmdline: argc \([0-9]*\) .*/\1/p' $S/cx.cmd)" "4"
	sed -n 's/^env [0-9]* //p' $S/cx.cmd | sort > $S/cx.env
	# gdb adds COLUMNS, LINES and PWD to the inferior's environment itself, so
	# the expected set is the 4 exported plus those 3, and nothing else.
	#
	# COLUMNS and LINES were pinned at 80 and 24, which are this gdb's batch
	# defaults rather than anything corex decides. The subject here is corex
	# recovering the environment out of the stack, so the four exported
	# variables are compared by name and value and gdb's three by name only.
	# Pinning gdb's idea of a terminal size would have failed the test on a
	# gdb that sized itself differently, about a corex that was right.
	printf 'COREX_MARK=hello\nHOME=/nonexistent\nLC_ALL=C\nPATH=/usr/bin\nPWD=%s\n' "$PWD" > $S/want.env
	grep -v '^COLUMNS=\|^LINES=' $S/cx.env > $S/cx.env.exported
	cmp -s $S/want.env $S/cx.env.exported && ok "the environment is exactly the 5 name=value pairs that were set" || {
		no "environment disagrees with what was exported"; diff $S/want.env $S/cx.env.exported; }
	# and gdb's two terminal variables are there, whatever it chose for them
	cnames=$(sed -n 's/^\(COLUMNS\|LINES\)=.*/\1/p' $S/cx.env | sort | tr '\n' ' ')
	chk "gdb's COLUMNS and LINES are recovered too" "$cnames" "COLUMNS LINES "
	# psargs is the same command line truncated to 80 bytes with NULs turned
	# into spaces, so it must be a prefix of what we reassembled.
	psa=$($COREX --proc $S/core.args | sed -n 's/^psargs: //p')
	full=$(sed -n 's/^arg [0-9]* //p' $S/cx.cmd | tr '\n' ' ')
	case "$full " in "$psa "*) ok "NT_PRPSINFO's pr_psargs is a prefix of the recovered argv" ;;
		*) no "pr_psargs [$psa] is not a prefix of [$full]" ;; esac
fi
# The real argv of the other cores must match what gen() ran.
got=$($COREX --cmdline $S/core.threads | sed -n 's/^arg [0-9]* //p' | tr '\n' ' ')
chk "argv of the threads core" "$got" "$PWD/$S/threads "

# -- a different signal: SIGABRT, which has no faulting address ------------
# abort() raises the signal against the process itself, so si_code is SI_TKILL
# and the siginfo union holds a sender pid and uid, not an address. A reader
# that prints si_addr unconditionally reports a nonsense faulting address here
# -- gdb shows the same bytes as _sigfault.si_addr = 0x3e8003c9c3c, which is
# just the pid and uid read as a pointer.
gen abrt || exit 1
ok "gcore: wrote a core for t/abrt.c"
gdbb $S/abrt $S/core.abrt -ex 'p $_siginfo' >$S/gdb.abrt 2>&1
want=$(sed -n 's/^Program terminated with signal \([A-Z0-9]*\),.*/\1/p' $S/gdb.abrt)
got=$($COREX --signal $S/core.abrt | sed -n 's/^signal: \([A-Z0-9]*\) .*/\1/p')
chk "killing signal agrees with gdb ($want)" "$got" "$want"
want=$(tr ',' '\n' <$S/gdb.abrt | sed -n 's/.*si_code = \(-*[0-9]*\).*/\1/p' | head -1)
got=$($COREX --signal $S/core.abrt | sed -n 's/^signal: .* code \(-*[0-9]*\) .*/\1/p')
chk "si_code agrees with gdb ($want, SI_TKILL)" "$got" "$want"
want=$(tr ',' '\n' <$S/gdb.abrt | sed -n 's/.*_kill = {si_pid = \([0-9]*\).*/\1/p' | head -1)
got=$($COREX --signal $S/core.abrt | sed -n 's/^fault: sent by pid \([0-9]*\) .*/\1/p')
chk "the sending pid agrees with gdb ($want)" "$got" "$want"
got=$($COREX --signal $S/core.abrt | sed -n 's/^fault: sent by pid [0-9]* uid \([0-9]*\)/\1/p')
chk "the sending uid is this user" "$got" "$(id -u)"
$COREX --signal $S/core.abrt | grep -q 'fault: address' && no "a faulting address was printed for SIGABRT" ||
	ok "no faulting address is claimed for SIGABRT"
bt_gdb $S/core.abrt $S/abrt > $S/gdb.btabrt
bt_cx $S/core.abrt 1 > $S/cx.btabrt
k=$(wc -l <$S/cx.btabrt | tr -d ' ')
# Here the skipped frames are in the middle, not at the end: the signal landed
# inside libc, which keeps no frame pointer, so rbp still points at boom()'s
# frame and the chain steps straight over raise() and abort().
if bt_subseq $S/gdb.btabrt $S/cx.btabrt; then
	ok "the $k frames of the SIGABRT backtrace are frames gdb also reports, in order (gdb reaches $(wc -l <$S/gdb.btabrt | tr -d ' '))"
else
	no "SIGABRT backtrace is not a subsequence of gdb's"
fi

